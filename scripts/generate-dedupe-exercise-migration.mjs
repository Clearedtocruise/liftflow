#!/usr/bin/env node
/**
 * Generates supabase/migrations/028_dedupe_duplicate_exercise_names.sql
 * Removes scaffold duplicate rows that share the same display name.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { loadExerciseCatalog } from './lib/parse-exercise-catalog.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

function loadPreferredSlugs() {
  const preferred = new Set();
  const mapPath = path.join(root, 'backend/src/lib/liftingReference/month1ExerciseSlugMap.ts');
  const mapText = fs.readFileSync(mapPath, 'utf8');
  for (const match of mapText.matchAll(/:\s*"([a-z0-9-]+)"/g)) {
    preferred.add(match[1]);
  }
  const catalogPath = path.join(root, 'src/constants/exerciseDatabase.ts');
  const catalogText = fs.readFileSync(catalogPath, 'utf8');
  for (const match of catalogText.matchAll(/slug:\s*'([^']+)'/g)) {
    preferred.add(match[1]);
  }
  return preferred;
}

function normalizeExerciseName(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

function slugifyExerciseName(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

const VARIANT_SUFFIX = /-(?:ch|ba|la|sh|tr|qd|hm|gl|cv|co|fa|nc|ca|fu|bi)[0-9]{2,4}$/i;

function isCatalogVariantSlug(slug) {
  return VARIANT_SUFFIX.test(slug);
}

function pickCanonicalExerciseSlug(name, slugs, preferredSlugs) {
  const unique = [...new Set(slugs)];
  if (unique.length === 1) return unique[0];

  const preferred = unique.filter((slug) => preferredSlugs.has(slug));
  if (preferred.length === 1) return preferred[0];
  if (preferred.length > 1) return preferred.sort((a, b) => a.length - b.length)[0];

  const base = slugifyExerciseName(name);
  if (unique.includes(base)) return base;

  const nonVariant = unique.filter((slug) => !isCatalogVariantSlug(slug));
  if (nonVariant.length > 0) return nonVariant.sort((a, b) => a.length - b.length)[0];

  return unique.sort((a, b) => a.length - b.length)[0];
}

function main() {
  const catalog = loadExerciseCatalog();
  const preferredSlugs = loadPreferredSlugs();
  const byName = new Map();

  for (const row of catalog) {
    const key = normalizeExerciseName(row.name);
    const list = byName.get(key) ?? [];
    list.push(row.slug);
    byName.set(key, list);
  }

  const remove = [];
  const keep = new Set();
  const remap = [];
  let duplicateGroupCount = 0;

  for (const [nameKey, slugs] of byName) {
    if (slugs.length === 1) {
      keep.add(slugs[0]);
      continue;
    }
    duplicateGroupCount += 1;
    const displayName = catalog.find((row) => normalizeExerciseName(row.name) === nameKey)?.name ?? nameKey;
    const canonical = pickCanonicalExerciseSlug(displayName, slugs, preferredSlugs);
    keep.add(canonical);
    for (const slug of slugs) {
      if (slug !== canonical) {
        remove.push(slug);
        remap.push({ fromSlug: slug, toSlug: canonical });
      }
    }
  }

  remove.sort();
  remap.sort((a, b) => a.fromSlug.localeCompare(b.fromSlug));

  const remapChunks = [];
  for (let i = 0; i < remap.length; i += 80) {
    remapChunks.push(remap.slice(i, i + 80));
  }

  const deleteChunks = [];
  for (let i = 0; i < remove.length; i += 40) {
    deleteChunks.push(remove.slice(i, i + 40));
  }

  const lines = [
    '-- Remove duplicate system exercises that share the same display name.',
    `-- Keeps ${keep.size} canonical exercises; removes ${remove.length} scaffold variant rows (${duplicateGroupCount} duplicate name groups).`,
    '-- Generated by scripts/generate-dedupe-exercise-migration.mjs',
    '',
    'create table if not exists public._migration_exercise_slug_remap (',
    '  from_slug text primary key,',
    '  to_slug text not null',
    ');',
    'truncate public._migration_exercise_slug_remap;',
    '',
  ];

  for (const chunk of remapChunks) {
    lines.push('insert into public._migration_exercise_slug_remap (from_slug, to_slug) values');
    lines.push(
      chunk
        .map(({ fromSlug, toSlug }) => `  ('${fromSlug}', '${toSlug}')`)
        .join(',\n') + ';',
    );
    lines.push('');
  }

  lines.push(
    '-- Drop custom-exercise rows that would violate unique(user_id, exercise_id) after remap.',
    'delete from public.user_custom_exercises uce',
    'using public.exercises dup',
    'join public._migration_exercise_slug_remap m on m.from_slug = dup.slug',
    'join public.exercises canon on canon.slug = m.to_slug',
    'where uce.exercise_id = dup.id',
    '  and exists (',
    '    select 1',
    '    from public.user_custom_exercises existing',
    '    where existing.user_id = uce.user_id',
    '      and existing.exercise_id = canon.id',
    '  );',
    '',
    'update public.workout_exercises we',
    'set exercise_id = canon.id',
    'from public.exercises dup',
    'join public._migration_exercise_slug_remap m on m.from_slug = dup.slug',
    'join public.exercises canon on canon.slug = m.to_slug',
    'where we.exercise_id = dup.id;',
    '',
    'update public.user_custom_exercises uce',
    'set exercise_id = canon.id',
    'from public.exercises dup',
    'join public._migration_exercise_slug_remap m on m.from_slug = dup.slug',
    'join public.exercises canon on canon.slug = m.to_slug',
    'where uce.exercise_id = dup.id;',
    '',
    'update public.performance_trends pt',
    'set exercise_id = canon.id',
    'from public.exercises dup',
    'join public._migration_exercise_slug_remap m on m.from_slug = dup.slug',
    'join public.exercises canon on canon.slug = m.to_slug',
    'where pt.exercise_id = dup.id;',
    '',
    'update public.exercise_recognition_events ere',
    'set suggested_exercise_id = canon.id',
    'from public.exercises dup',
    'join public._migration_exercise_slug_remap m on m.from_slug = dup.slug',
    'join public.exercises canon on canon.slug = m.to_slug',
    'where ere.suggested_exercise_id = dup.id;',
    '',
  );

  for (const chunk of deleteChunks) {
    lines.push('delete from public.exercises');
    lines.push('where is_system = true');
    lines.push(`  and slug in (${chunk.map((slug) => `'${slug}'`).join(', ')});`);
    lines.push('');
  }

  lines.push(
    'drop table if exists public._migration_exercise_slug_remap;',
    '',
    'create unique index if not exists exercises_system_unique_name_idx',
    '  on public.exercises (lower(trim(name)))',
    '  where is_system = true;',
    '',
  );

  const outPath = path.join(root, 'supabase/migrations/028_dedupe_duplicate_exercise_names.sql');
  fs.writeFileSync(outPath, lines.join('\n'));
  console.log(`Wrote ${outPath}`);
  console.log(`Removing ${remove.length} duplicate slugs across ${duplicateGroupCount} duplicate name groups`);
}

main();
